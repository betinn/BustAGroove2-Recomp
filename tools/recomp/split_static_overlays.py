#!/usr/bin/env python3
"""Split the monolithic overlays_static.c emitted by the kem0x/psxrecomp fork's
`compile_overlays.py --static` into one translation unit per overlay and generate a
variant-aware dispatcher.

The fork's dispatcher is a plain `switch (addr)` with no idea of WHICH overlay currently
occupies an address, so overlays that share a load address (36 character overlays at
0x801CC510, ...) produce duplicate symbols and duplicate cases. This tool:
  1. cuts the file at every "Generated by PSXRecomp" header (one part per overlay),
  2. makes every `func_XXXXXXXX` in a part `static` and appends a per-part dispatcher,
  3. identifies the overlay record each part was compiled from (instruction comments
     `/* 0xADDR: 0xWORD */` matched against the record bytes),
  4. emits overlays_dispatch.c: per load region, the variants with a 16-byte signature
     (first bytes of the payload) that is compared against guest RAM before dispatching.

Usage: split_static_overlays.py <overlays_static.c> <static-inputs.json> <out dir>
"""
import base64, json, os, re, struct, sys, zlib

src_path, inputs_path, out_dir = sys.argv[1:4]
os.makedirs(out_dir, exist_ok=True)
src = open(src_path, encoding='utf-8', errors='replace').read()
recs = json.load(open(inputs_path))

MARKER = '/* Generated by PSXRecomp - PlayStation 1 Static Recompiler */'
disp_idx = src.rfind('/* Auto-generated overlay dispatch')
parts = src[:disp_idx].split(MARKER)[1:]

# ---- records: payload bytes at producer range ------------------------------------------
records = []
for i, r in enumerate(recs):
    data = base64.b64decode(r['bytes_b64'])
    load = int(r['load_addr'], 16)
    pr = r['producer_ranges'][0]
    base, end = int(pr['start'], 16), int(pr['end'], 16)
    payload = data[base - load:end - load]
    records.append({'idx': i, 'load': load, 'data': data, 'base': base, 'end': end,
                    'payload': payload, 'crc': zlib.crc32(data) & 0xffffffff})

def word_at(rec, addr):
    off = addr - rec['load']
    if off < 0 or off + 4 > len(rec['data']): return None
    return struct.unpack_from('<I', rec['data'], off)[0]

def match_record(part):
    pairs = re.findall(r'/\* 0x([0-9A-F]{8}): 0x([0-9A-F]{8}) \*/', part)
    if not pairs: return None
    sample = pairs[::max(1, len(pairs) // 64)][:64]
    best, best_n = None, -1
    for rec in records:
        n = sum(1 for a, w in sample if word_at(rec, int(a, 16)) == int(w, 16))
        if n > best_n: best, best_n = rec, n
    return best if best_n == len(sample) else None

# ---- per-part units --------------------------------------------------------------------
units = []  # (unit index, record)
for pi, part in enumerate(parts):
    rec = match_record(part)
    if rec is None:
        print(f'part {pi}: no matching record, skipped'); continue
    defs = re.findall(r'^void (func_[0-9A-F]+)\(CPUState\* cpu\)\s*\{', part, re.M)
    body = MARKER + part
    # prototypes and definitions become static (names only collide across units otherwise)
    body = re.sub(r'^void (func_[0-9A-F]+)\(CPUState\* cpu\);', r'static void \1(CPUState* cpu);', body, flags=re.M)
    body = re.sub(r'^void (func_[0-9A-F]+)\(CPUState\* cpu\)(\s*\{)', r'static void \1(CPUState* cpu)\2', body, flags=re.M)
    ui = len(units)
    cases = '\n'.join(f'        case 0x{d[5:]}u: {d}(cpu); return 1;' for d in sorted(set(defs)))
    body += f'''

/* ---- bag2: per-overlay dispatcher (record {rec['idx']}, load {rec['base']:#x}, crc32 {rec['crc']:08X}) ---- */
int bag2_ov_{ui:03d}_dispatch(CPUState *cpu, uint32_t addr) {{
    switch (addr) {{
{cases}
        default: return 0;
    }}
}}
'''
    with open(os.path.join(out_dir, f'ov_{ui:03d}.c'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(body)
    units.append((ui, rec))
    print(f'part {pi} -> ov_{ui:03d}.c record {rec["idx"]} load {rec["base"]:#x} funcs {len(set(defs))}')

# ---- dispatcher ------------------------------------------------------------------------
SIG = 16
regions = {}
for ui, rec in units:
    regions.setdefault(rec['base'], []).append((ui, rec))
lines = ['/* bag2: variant-aware static overlay dispatcher (generated by split_static_overlays.py) */',
         '#include <stdint.h>', '#include <string.h>', '#include "psx_runtime.h"',
         'extern uint8_t *memory_get_ram_ptr(void);', '']
for ui, _ in units:
    lines.append(f'int bag2_ov_{ui:03d}_dispatch(CPUState *cpu, uint32_t addr);')
lines.append('')
lines.append('typedef struct { const uint8_t sig[%d]; int (*dispatch)(CPUState *, uint32_t); } bag2_variant;' % SIG)
lines.append('typedef struct { uint32_t base, end; int count; const bag2_variant *v; int last; } bag2_region;')
reg_defs = []
for ri, (base, items) in enumerate(sorted(regions.items())):
    sigs = set()
    vlines = []
    for ui, rec in items:
        s = rec['payload'][:SIG]
        assert s not in sigs, f'signature collision in region {base:#x}'
        sigs.add(s)
        vlines.append('    { {' + ', '.join(f'0x{b:02X}' for b in s) + f'}}, bag2_ov_{ui:03d}_dispatch }},')
    end = max(rec['end'] for _, rec in items)
    lines.append(f'static const bag2_variant bag2_r{ri}_v[] = {{')
    lines += vlines
    lines.append('};')
    reg_defs.append(f'    {{ 0x{base:08X}u, 0x{end:08X}u, {len(items)}, bag2_r{ri}_v, -1 }},')
lines.append('static bag2_region bag2_regions[] = {')
lines += reg_defs
lines.append('};')
lines.append('''
/* Called by dirty_ram_interp.c before interpreting a PC inside dirty RAM. The overlay
 * currently loaded at a region is recognised by the first bytes of its payload, so the
 * right native variant is dispatched (or none, and the interpreter runs). */
int psx_overlay_dispatch(CPUState *cpu, uint32_t addr) {
    const uint8_t *ram = memory_get_ram_ptr();
    for (unsigned ri = 0; ri < sizeof(bag2_regions) / sizeof(bag2_regions[0]); ri++) {
        bag2_region *r = &bag2_regions[ri];
        if (addr < r->base || addr >= r->end) continue;
        const uint8_t *here = ram + (r->base & 0x1FFFFFu);
        if (r->last >= 0 && memcmp(here, r->v[r->last].sig, %d) == 0)
            return r->v[r->last].dispatch(cpu, addr);
        for (int i = 0; i < r->count; i++) {
            if (memcmp(here, r->v[i].sig, %d) == 0) { r->last = i; return r->v[i].dispatch(cpu, addr); }
        }
        return 0;
    }
    return 0;
}
''' % (SIG, SIG))
with open(os.path.join(out_dir, 'overlays_dispatch.c'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('\n'.join(lines))
print(f'{len(units)} units, {len(regions)} regions -> {out_dir}')
